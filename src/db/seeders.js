/**
 * Seed master data (categories and food catalog) idempotently.
 * Never inserts dummy user balances or fake transactions.
 * @param {import('./database.js').DatabaseAdapter} db
 */
export async function seedMasterData(db) {
  const now = toIsoUtc();

  const existingCatCount = await db.queryOne('SELECT COUNT(*) AS cnt FROM categories');
  if (!existingCatCount || existingCatCount.cnt === 0) {
    for (const cat of DEFAULT_CATEGORIES) {
      await db.run(
        `INSERT OR IGNORE INTO categories (id, name, type, icon, color, is_default, created_at, updated_at, deleted_at)
         VALUES (?, ?, ?, ?, ?, ?, ?, ?, NULL)`,
        [cat.id, cat.name, cat.type, cat.icon, cat.color, cat.is_default, now, now]
      );
    }
  }

  const existingFoodCount = await db.queryOne('SELECT COUNT(*) AS cnt FROM food_items');
  if (!existingFoodCount || existingFoodCount.cnt < DEFAULT_FOOD_ITEMS.length) {
    for (const food of DEFAULT_FOOD_ITEMS) {
      await db.run(
        `INSERT OR IGNORE INTO food_items (
          id, name, default_price, estimated_price, calories, protein,
          food_category, preparation_type, required_equipment, suitable_meal_types,
          ingredients, instructions, tags, has_protein, has_vegetable,
          is_favorite, is_custom, created_at, updated_at, deleted_at
        ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, 0, 0, ?, ?, NULL)`,
        [
          food.id,
          food.name,
          food.default_price,
          food.default_price,
          food.calories,
          food.protein,
          food.food_category,
          food.preparation_type,
          food.required_equipment,
          JSON.stringify(food.suitable_meal_types),
          JSON.stringify(food.ingredients),
          food.instructions,
          JSON.stringify(food.tags),
          food.has_protein,
          food.has_vegetable,
          now,
          now
        ]
      );
    }
  }
}
